# 发送飞书消息的函数
def send_feishu(msg):
    data = {
        "msg_type": "text",
        "content": {"text": msg}
    }
    try:
        requests.post(FEISHU_WEBHOOK, json=data, timeout=10)
        print("飞书消息发送成功")
    except Exception as e:
        print(f"发送失败：{e}")

